"""Render the results block of README.md from eval/results/*.json (and the cost ledger).

Every number in the block is read from a result file; nothing is typed here. The block sits between
``<!-- results:start -->`` and ``<!-- results:end -->``; the prose around it is written by hand and
contains no figures from the results (a test checks that the README's block is current).

Usage: uv run python eval/render_readme.py [--check]   (--check fails if README.md is out of date)
"""

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"
RESULTS = ROOT / "eval" / "results"


def load(name: str) -> dict[str, Any]:
    """Read one result file."""
    return json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))


def pct(x: float, digits: int = 1) -> str:
    """Format a share as a percentage with a thin space before the sign."""
    return f"{100 * x:.{digits}f} %"


def ledger_total() -> float:
    """Return the sum of the committed ledger of paid model calls."""
    rows = (ROOT / "eval" / "usage" / "ledger.jsonl").read_text(encoding="utf-8").splitlines()
    return round(sum(json.loads(r)["cost_usd"] for r in rows if r.strip()), 4)


