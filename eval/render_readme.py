# ruff: noqa: E501
"""Render the results block of README.md from eval/results/*.json (and the cost ledger).

Every number in the block is read from a result file; nothing is typed here. The block sits between
``<!-- results:start -->`` and ``<!-- results:end -->``; the prose around it is written by hand and
contains no figures from the results (a test checks that the README's block is current).

Usage: uv run python eval/render_readme.py [--check]   (--check fails if README.md is out of date)
"""

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"
RESULTS = ROOT / "eval" / "results"


def load(name: str) -> dict[str, Any]:
    """Read one result file."""
    return json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))


def pct(x: float, digits: int = 1) -> str:
    """Format a share as a percentage with a thin space before the sign."""
    return f"{100 * x:.{digits}f} %"


def ledger_total() -> float:
    """Return the sum of the committed ledger of paid model calls."""
    rows = (ROOT / "eval" / "usage" / "ledger.jsonl").read_text(encoding="utf-8").splitlines()
    return round(sum(json.loads(r)["cost_usd"] for r in rows if r.strip()), 4)


def render() -> str:
    """Return the generated block."""
    b, c2 = load("c1")["summary"], load("c2")
    base, c1 = b["baseline"], b["c1"]
    c3, c4, c5, c6 = load("c3"), load("c4"), load("c5"), load("c6")
    c7, c8, rag = load("c7"), load("c8"), load("rag")
    held = load("c1")["held_out_months"]
    t3 = c3["test_2025"]
    t4 = c4["test_2025"]
    t5 = c5["test_2025"]
    t6 = c6["test_2025"]
    modes = rag["test"]["modes"]
    llm, sta = c7["test"]["llm"], c7["test"]["standin"]
    g = c8["gates"]
    lines = [
        START,
        "*Generated by `eval/render_readme.py` from `eval/results/*.json`. Do not edit by hand.*",
        "",
        "### The optimizer against the manual roster (C1, held-out months " + held + ")",
        "",
        "| Measure | Manual roster (simulated baseline) | C1 (recommended variant) |",
        "|---|---|---|",
        f"| Hard-rule violations, published rosters (counted by C2) | {base['hard_violations']} | "
        f"{c1['hard_violations']} |",
        f"| Wishes granted | {pct(base['wishes_granted_rate'])} | {pct(c1['wishes_granted_rate'])} |",
        f"| Important wishes granted | {pct(base['important_wishes_granted_rate'])} | "
        f"{pct(c1['important_wishes_granted_rate'])} |",
        f"| Overtime hours (sum over the months) | {base['overtime_hours']} | {c1['overtime_hours']} |",
        f"| Burden spread (mean per month) | {base['burden_spread_mean']} | {c1['burden_spread_mean']} |",
        f"| Isolated single nights | {base['isolated_nights']} | {c1['isolated_nights']} |",
        "",
        f"The independent validator (C2) agrees with the second checker on "
        f"{c2['summary']['agreement_published_months']} published months and "
        f"{c2['summary']['agreement_random_changes']} random changes. Median solve time "
        f"{load('c1')['median_seconds_per_variant']} s per variant (wall clock on one machine).",
        "",
        "### Where the simple model won",
        "",
        "Each learned component was compared with a simple baseline by a rule written before the "
        "held-out year (2025) was scored. None of the four learners was promoted.",
        "",
        "| Component | Simple baseline (served) | Challenger | Held-out result |",
        "|---|---|---|---|",
        f"| C3 absence forecast | seasonal naive: MAE {t3['seasonal_naive']['mae']:.3f}, "
        f"deviance {t3['seasonal_naive']['poisson_deviance']:.3f} | LightGBM: MAE "
        f"{t3['lightgbm']['mae']:.3f}, deviance {t3['lightgbm']['poisson_deviance']:.3f} | "
        "baseline better; not promoted |",
        f"| C4 preference learner (wish / avoid log-likelihood, higher is better) | raw rates: "
        f"{t4['raw']['wish']['mean_ll']:.4f} / {t4['raw']['avoid']['mean_ll']:.4f} | hierarchical: "
        f"{t4['hierarchical']['wish']['mean_ll']:.4f} / {t4['hierarchical']['avoid']['mean_ll']:.4f} | "
        "differences inside the bootstrap interval; not promoted |",
        f"| C5 cover ranker (acceptance, Brier, lower is better; AUC) | base rate: "
        f"{t5['base_rate']['brier']:.4f}; AUC {t5['base_rate']['auc']:.2f} | LightGBM: "
        f"{t5['lightgbm']['brier']:.4f}; AUC {t5['lightgbm']['auc']:.3f} | no gain; not promoted |",
        f"| C6 leave feasibility (precision / recall of a yes, pooled with simulated stress states) | "
        f"logistic regression: {t6['logistic']['pooled']['precision']:.3f} / "
        f"{t6['logistic']['pooled']['recall']:.3f} | LightGBM: {t6['lightgbm']['pooled']['precision']:.3f} / "
        f"{t6['lightgbm']['pooled']['recall']:.3f} | precision margin not met, recall lower; not promoted |",
        f"| Rule search recall@5 ({rag['test']['modes']['hybrid']['n_answerable']} answerable test "
        f"questions) | vectors alone: {modes['vector']['recall@5']:.3f} | hybrid (full text + vectors): "
        f"{modes['hybrid']['recall@5']:.3f}; full text alone: {modes['fts']['recall@5']:.3f} | "
        "vectors alone served; the pre-registered check for hybrid failed |",
        "",
        "### The language-model agents, against rules written before the first call",
        "",
        f"**C7 request intake** (`{c7['model']}`, {llm['n']} test utterances): whole preference set "
        f"correct {pct(llm['exact_match'])} for the model against {pct(sta['exact_match'])} for the "
        f"keyword stand-in, but one planted instruction was followed "
        f"({llm['injections_followed']} of {llm['injections']}), so the rule failed and "
        f"**{'the model is served' if c7['promoted'] else 'the stand-in is served'}**.",
        "",
        f"**C8 planner copilot** (`{c8['model']}`, {c8['test']['tasks']} test tasks, run once):",
        "",
        "| Gate | Result |",
        "|---|---|",
        f"| Planted instructions followed | {g['S1_injection']['followed']} (passed) |",
        f"| Runs that changed anything but a proposal | {g['S2_no_publish_or_approve']['runs_with_state_change']} "
        f"(passed) |",
        f"| Privacy findings in all texts sent to the model | {g['S3_privacy']['findings']} in "
        f"{g['S3_privacy']['runs_scanned']} runs (passed) |",
        f"| Lookups | {g['K1_lookups']['correct']} of {g['K1_lookups']['of']} "
        f"({'passed' if g['K1_lookups']['pass'] else 'failed'}) |",
        f"| Rule questions | {g['K2_rules']['correct']} of {g['K2_rules']['of']} "
        f"({'passed' if g['K2_rules']['pass'] else 'failed'}) |",
        f"| What-ifs | {g['K3_whatifs']['correct']} of {g['K3_whatifs']['of']} "
        f"({'passed' if g['K3_whatifs']['pass'] else 'failed'}) |",
        f"| Drafting | {g['K4_drafting']['correct']} of {g['K4_drafting']['of']} "
        f"({'passed' if g['K4_drafting']['pass'] else 'failed'}) |",
        "",
        "Served by the agent: "
        + ", ".join(k for k, v in c8["served"].items() if v)
        + ". Answered by the keyword stand-in: "
        + ", ".join(k for k, v in c8["served"].items() if not v)
        + ".",
        "",
        f"All paid model calls of the project (ledger): ${ledger_total():.2f} of the "
        f"${c8['cost']['phase_limit_usd']:.2f} limit.",
        END,
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Write or check the block in README.md."""
    text = README.read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    new = text[:start] + render() + text[end:]
    if "--check" in argv:
        if new != text:
            print("README.md results block is out of date; run eval/render_readme.py")
            return 1
        return 0
    README.write_text(new, encoding="utf-8")
    print("rendered the README results block")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
