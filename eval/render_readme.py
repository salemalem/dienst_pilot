def main(argv: list[str]) -> int:
    """Write or check the generated blocks in README.md and docs/CV_ENTRY.md."""
    todo = [(README, START, END, render), (CV, CV_START, CV_END, render_cv)]
    stale = False
    for path, a, z, fn in todo:
        text = path.read_text(encoding="utf-8")
        start, end = text.index(a), text.index(z) + len(z)
        new = text[:start] + fn() + text[end:]
        if "--check" in argv:
            if new != text:
                print(f"{path.relative_to(ROOT)} is out of date; run eval/render_readme.py")
                stale = True
        else:
            path.write_text(new, encoding="utf-8")
    if "--check" in argv:
        return 1 if stale else 0
    print("rendered the README results block and the CV bullets")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
