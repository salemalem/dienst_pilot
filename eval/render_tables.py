"""Render the §17.1 table in docs/ARCHITECTURE.md and the C3 and C4 tables in the model cards.

Sources: eval/results/benchmark.json, c3.json, c4.json and c5.json.

Usage: uv run python eval/render_tables.py [--check]   (--check fails if the doc is out of date)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "ARCHITECTURE.md"
START, END = "<!-- benchmark:start -->", "<!-- benchmark:end -->"
CARD = ROOT / "docs" / "model-cards" / "c3-absence-forecaster.md"
C3_START, C3_END = "<!-- c3:start -->", "<!-- c3:end -->"
C4_CARD = ROOT / "docs" / "model-cards" / "c4-preference-learner.md"
C4_START, C4_END = "<!-- c4:start -->", "<!-- c4:end -->"
C5_CARD = ROOT / "docs" / "model-cards" / "c5-cover-ranker.md"
C5_START, C5_END = "<!-- c5:start -->", "<!-- c5:end -->"
C5_MODELS = {
    "base_rate": "Base rate (baseline B1)",
    "logistic": "Logistic regression (baseline B2)",
    "lightgbm": "LightGBM + isotonic calibration (learner)",
}
C5_POLICIES = {
    "fairness_first_champion": "(a) Fairness first, buckets of two, champion inside a bucket",
    "stand_in": "(b) Previous stand-in: least burden, then hours",
    "most_reliable_first": "(c) Most reliable person first",
    "fairness_first_exact_buckets_sensitivity": "(a-exact) Fairness first, exact burden (sensitivity check)",
}
C4_MODELS = {
    "pooled": "Department rates (baseline B1)",
    "raw": "Own rates, no shrinkage (baseline B2)",
    "hierarchical": "Hierarchical Beta-Binomial (learner)",
}
MODELS = {
    "seasonal_naive": "Seasonal naive (baseline)",
    "poisson_glm": "Poisson GLM (baseline)",
    "nb_glm": "Negative-binomial GLM (baseline)",
    "lightgbm": "LightGBM (challenger)",
}


def table(doc: dict) -> str:  # type: ignore[type-arg]
    """Return the markdown table for the benchmark document."""
    b, c = doc["summary"]["baseline"], doc["summary"]["c1"]
    months = doc["held_out_months"]
    period = f"{months[0][:7]} to {months[-1][:7]}" if len(months) > 1 else months[0][:7]
    t = doc["timing"]
    lines = [
        START,
        f"*Generated by `eval/render_tables.py` from `eval/results/benchmark.json` ({len(months)} held-out months, "
        f"{period}; dataset seed {doc['dataset']['seed']}, generator {doc['dataset']['generator_version']}; "
        f"solver {doc['versions']['solver']}, validator {doc['versions']['validator']}). Do not edit by hand.*",
        "",
        "| Metric | Manual baseline | DienstPilot (C1) |",
        "|---|---|---|",
        f"| Hard-rule violations, published rosters (counted by C2) | {b['hard_violations']} | {c['hard_violations']} |",
        f"| Hard-rule violations, in-month changes (simulation parameter, see note) | {b['in_month_violations']} | — |",
        f"| Wishes granted | {b['wishes_granted_rate']:.1%} | {c['wishes_granted_rate']:.1%} |",
        f"| Important wishes granted | {b['important_wishes_granted_rate']:.1%} | {c['important_wishes_granted_rate']:.1%} |",
        f"| Weighted-burden spread (max − min, mean per month) | {b['burden_spread_mean']} | {c['burden_spread_mean']} |",
        f"| Overtime hours (sum) | {b['overtime_hours']} | {c['overtime_hours']} |",
        f"| Isolated single nights (sum) | {b['isolated_nights']} | {c['isolated_nights']} |",
        f"| Solve time per variant (median, wall clock, not reproducible) | — | {t['median_seconds_per_variant']} s |",
        "",
        f"C1 is the recommended variant (profile `{doc['config']['recommended_profile']}`), its weights tuned on "
        f"{doc['tuning_months'][0][:7]} to {doc['tuning_months'][-1][:7]} (`eval/results/tuning.json`). "
        f"Results hash `{doc['results_sha256'][:12]}`.",
        "",
        "Limitations: " + " ".join(doc["limitations"]),
        END,
    ]
    return "\n".join(lines)


def c3_tables(doc: dict) -> str:  # type: ignore[type-arg]
    """Return the markdown tables of the C3 model card."""
    cv, test, champ = doc["cv_2022_2024"], doc["test_2025"], doc["champion"]
    v = doc["versions"]
    rows = [
        f"| {label}{' **(served)**' if k == champ['kind'] else ''} "
        f"| {cv[k]['mean_poisson_deviance']:.3f} | {cv[k]['mean_mae']:.3f} "
        f"| {test[k]['poisson_deviance']:.3f} | {test[k]['mae']:.3f} "
        f"| {test[k]['coverage_80']:.1%} | {test[k]['mean_interval_width']:.2f} |"
        for k, label in MODELS.items()
    ]
    checks = doc["promotion"]["checks"]
    ci = checks["bootstrap_ci_excludes_zero_in_favour"]["difference_challenger_minus_baseline_95ci"]
    dev, mae = checks["deviance_at_least_2pct_lower"], checks["mae_not_worse_than_2pct"]
    cov = checks["coverage_80_in_75_to_85_and_not_3pt_worse"]
    mark = {True: "passed", False: "failed"}
    bucket_rows = [
        f"| {label} | {b['rows']} | {b['mae']:.3f} | {b['poisson_deviance']:.3f} | {b['coverage_80']:.1%} |"
        for label, b in test[champ["kind"]]["by_horizon"].items()
    ]
    ref = doc["truth_recovery"]["reference"]
    tr = doc["truth_recovery"]["models"][champ["kind"]]
    tr_rows = [
        f"| {h[1:]} days | {e['corr_28d_smoothed_with_true']:.2f} | {e['winter_peak_day_error_days']:+d} "
        f"| {e['winter_peak_amplitude_ratio']:.2f} | {e['mean_ratio_forecast_to_true']:.2f} |"
        for h, e in tr.items()
    ]
    lines = [
        C3_START,
        "*Generated by `eval/render_tables.py` from `eval/results/c3.json`. Do not edit by hand.*",
        "",
        f"Data: seed {v['data']['seed']}, generator {v['data']['generator_version']}, manifest `{v['data']['manifest_sha256'][:12]}`. "
        f"Code: C3 sources `{v['code']['ml_sources_sha256'][:12]}`, promotion rule `{v['code']['promotion_rule_sha256'][:12]}`, "
        f"served bundle `{champ['bundle_sha256'][:12]}` (registry version {champ['registry_version']}).",
        "",
        "Cross-validation: rolling origin, six expanding folds over 2022 to 2024 (mean over folds). "
        f"Test: 2025, {doc['split']['test_rows']} (origin, horizon) rows, scored once.",
        "",
        "| Model | CV Poisson deviance | CV MAE | 2025 Poisson deviance | 2025 MAE | 2025 coverage of the 80 % interval | Mean interval width |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        f"Best baseline by cross-validation (rule step 1): `{champ['best_baseline_by_cv']}`. "
        f"Challenger promoted: **{'yes' if champ['promoted_challenger'] else 'no'}**. Promotion checks on 2025:",
        "",
        "| Check (PROMOTION_RULE.md) | Result | Value |",
        "|---|---|---|",
        f"| 1. Deviance at least 2 % lower | {mark[dev['passed']]} | {dev['relative_change']:+.1%} |",
        f"| 2. Bootstrap 95 % interval of the deviance difference excludes zero | {mark[checks['bootstrap_ci_excludes_zero_in_favour']['passed']]} | [{ci[0]:+.3f}, {ci[1]:+.3f}] |",
        f"| 3. MAE not worse by more than 2 % | {mark[mae['passed']]} | {mae['relative_change']:+.1%} |",
        f"| 4. Coverage 75 to 85 % and not 3 points worse than the baseline | {mark[cov['passed']]} | {cov['challenger']:.1%} vs {cov['best_baseline']:.1%} |",
        "",
        f"Served model (`{champ['kind']}`) by forecast horizon, 2025:",
        "",
        "| Horizon | Rows | MAE | Poisson deviance | Coverage of the 80 % interval |",
        "|---|---|---|---|---|",
        *bucket_rows,
        "",
        "Recovery of the generator's true seasonal pattern (`eval/` only; reference = the generator's hazard "
        f"convolved with the episode length, mean {ref['mean_true_expected']:.2f} against {ref['mean_realised']:.2f} realised absent people per day in 2025). "
        "Served model, 2025:",
        "",
        "| Forecast made | Correlation with the true expectation (28-day smoothed) | Winter peak: day error | Winter peak: amplitude ratio | Mean forecast / mean truth |",
        "|---|---|---|---|---|",
        *tr_rows,
        C3_END,
    ]
    return "\n".join(lines)


def c4_tables(doc: dict) -> str:  # type: ignore[type-arg]
    """Return the markdown tables of the C4 model card."""
    cv, test, champ, v = doc["cv_2022_2024"], doc["test_2025"], doc["champion"], doc["versions"]
    mark = {True: "passed", False: "failed"}
    rows = [
        f"| {label}{' **(served)**' if k == champ['kind'] else ''} "
        f"| {cv[k]['mean_wish_ll']:.4f} | {cv[k]['mean_avoid_ll']:.4f} "
        f"| {test[k]['wish']['mean_ll']:.4f} | {test[k]['avoid']['mean_ll']:.4f} |"
        for k, label in C4_MODELS.items()
    ]
    little = [
        f"| {label} | {test[k]['wish']['mean_ll_little_history']:.4f} "
        f"| {test[k]['avoid']['mean_ll_little_history']:.4f} "
        f"| {test[k]['wish']['mean_ll_rest']:.4f} | {test[k]['avoid']['mean_ll_rest']:.4f} |"
        for k, label in C4_MODELS.items()
    ]
    ch = doc["promotion"]["checks"]
    names = {
        "ll_margin": "1. Log-likelihood higher by at least 0.5 % of the baseline's",
        "bootstrap_ci_excludes_zero": "2. Bootstrap 95 % interval of the difference excludes zero",
        "little_history_not_below_pooled": "3. Little-history group not below the pooled baseline",
    }
    check_rows = []
    for proc in ("wish", "avoid"):
        for key, label in names.items():
            c = ch[f"{proc}_{key}"]
            if key == "ll_margin":
                val = f"{c['difference']:+.5f} (needed {c['required_difference']:+.5f})"
            elif key == "bootstrap_ci_excludes_zero":
                val = f"[{c['difference_95ci'][0]:+.5f}, {c['difference_95ci'][1]:+.5f}]"
            else:
                val = f"{c['learner']:.4f} vs {c['pooled']:.4f}"
            check_rows.append(f"| {proc} | {label} | {mark[c['passed']]} | {val} |")
    tr = doc["truth_recovery"]["models"]
    tr_full = []
    for k, label in C4_MODELS.items():
        g = tr[k]
        f = lambda x: "n/a" if x is None else f"{x:.2f}"  # noqa: E731
        tr_full.append(
            f"| {label} | {f(g['all']['mean_spearman_vs_affinity'])} "
            f"| {f(g['rest']['mean_spearman_vs_affinity'])} "
            f"| {f(g['little_history']['mean_spearman_vs_affinity'])} "
            f"| {f(g['all']['mean_spearman_vs_pure_preference'])} |"
        )
    sp = doc["split"]
    lines = [
        C4_START,
        "*Generated by `eval/render_tables.py` from `eval/results/c4.json`. Do not edit by hand.*",
        "",
        f"Data: seed {v['data']['seed']}, generator {v['data']['generator_version']}, manifest `{v['data']['manifest_sha256'][:12]}`. "
        f"Code: C4 sources `{v['code']['c4_sources_sha256'][:12]}`, promotion rule `{v['code']['promotion_rule_sha256'][:12]}`, "
        f"served bundle `{champ['bundle_sha256'][:12]}` (registry version {champ['registry_version']}).",
        "",
        f"Mean log-likelihood per opportunity (nats; higher is better). Cross-validation: rolling origin by year, test years 2022 to 2024. "
        f"Test: 2025, {sp['test_people']} people with opportunities, posterior frozen at the end of 2024, scored once.",
        "",
        "| Model | CV wishes | CV swapped away | 2025 wishes | 2025 swapped away |",
        "|---|---|---|---|---|",
        *rows,
        "",
        f"Best baseline by cross-validation (rule step 1): `{champ['best_baseline_by_cv']}`. "
        f"Learner promoted: **{'yes' if champ['promoted_learner'] else 'no'}**. Promotion checks on 2025, for both processes:",
        "",
        "| Process | Check (PROMOTION_RULE.md) | Result | Value |",
        "|---|---|---|---|",
        *check_rows,
        "",
        f"People with little history ({sp['little_history_definition']}): {sp['test_people_little_history']} of the {sp['test_people']} test people. "
        "2025 mean log-likelihood by group:",
        "",
        "| Model | Little history: wishes | Little history: swapped away | Others: wishes | Others: swapped away |",
        "|---|---|---|---|---|",
        *little,
        "",
        f"Recovery of the generator's latent preferences (`eval/` only; {doc['truth_recovery']['cells_used']} cells per person, mean Spearman rank correlation per person, "
        f"{doc['truth_recovery']['people']} people, models fitted on 2021 to 2024; the pooled baseline ranks cells the same way for everybody):",
        "",
        "| Model | All people | Others | Little history | Against the pure weekday x shift preference |",
        "|---|---|---|---|---|",
        *tr_full,
        C4_END,
    ]
    return "\n".join(lines)


def c5_tables(doc: dict) -> str:  # type: ignore[type-arg]
    """Return the markdown tables of the C5 model card."""
    cv, test, champ, v = doc["cv_2022_2024"], doc["test_2025"], doc["champion"], doc["versions"]
    mark = {True: "passed", False: "failed"}
    rows = [
        f"| {label}{' **(served)**' if k == champ['kind'] else ''} "
        f"| {cv[k]['mean_brier']:.4f} | {cv[k]['mean_auc']:.3f} "
        f"| {test[k]['brier']:.4f} | {test[k]['auc']:.3f} | {test[k]['ece']:.3f} |"
        for k, label in C5_MODELS.items()
    ]
    ch = doc["promotion"]["checks"]
    b, a, u, e = (
        ch["brier_margin"],
        ch["brier_bootstrap_ci_excludes_zero"],
        ch["auc_higher_and_at_least_floor"],
        ch["ece_at_most_ceiling"],
    )
    checks = [
        f"| 1. Brier lower by at least 2 % of the baseline's | {mark[b['passed']]} "
        f"| {b['difference']:+.5f} (needed {b['required_difference']:+.5f}) |",
        f"| 2. Bootstrap 95 % interval of the Brier difference excludes zero | {mark[a['passed']]} "
        f"| [{a['difference_95ci'][0]:+.5f}, {a['difference_95ci'][1]:+.5f}] |",
        f"| 3. AUC higher than the baseline's and at least {u['floor']} | {mark[u['passed']]} "
        f"| {u['learner']:.3f} vs {u['best_baseline']:.3f} |",
        f"| 4. Calibration error at most {e['ceiling']} | {mark[e['passed']]} | {e['learner']:.3f} |",
    ]
    rp = doc["replay_2025"]
    pol, diff = rp["policies"], rp["paired_difference_to_stand_in"]

    def cell(name: str, metric: str, nd: int, pct: bool = False) -> str:
        m = pol[name][metric]
        f = (lambda x: f"{x * 100:.1f} %") if pct else (lambda x: f"{x:.{nd}f}")
        return f"{f(m['mean'])} ({f(m['p2_5'])} to {f(m['p97_5'])})"

    replay = [
        f"| {label} | {cell(k, 'time_to_fill_mean_min', 1)} | {cell(k, 'cover_burden_gini', 3)} "
        f"| {cell(k, 'escalation_rate', 1, True)} | {cell(k, 'contacted_per_filled_gap', 2)} |"
        for k, label in C5_POLICIES.items()
    ]

    def d(name: str, metric: str, nd: int) -> str:
        m = diff[name][metric]
        return f"{m['mean']:+.{nd}f} ({m['p2_5']:+.{nd}f} to {m['p97_5']:+.{nd}f})"

    paired = [
        f"| {label} | {d(k, 'time_to_fill_mean_min', 1)} | {d(k, 'cover_burden_gini', 3)} "
        f"| {d(k, 'escalation_rate', 3)} | {d(k, 'contacted_per_filled_gap', 2)} |"
        for k, label in C5_POLICIES.items()
        if k != "stand_in"
    ]
    sp = doc["split"]
    lines = [
        C5_START,
        "*Generated by `eval/render_tables.py` from `eval/results/c5.json`. Do not edit by hand.*",
        "",
        f"Data: seed {v['data']['seed']}, generator {v['data']['generator_version']}, manifest `{v['data']['manifest_sha256'][:12]}`. "
        f"Code: C5 sources `{v['code']['c5_sources_sha256'][:12]}`, promotion rule `{v['code']['promotion_rule_sha256'][:12]}`, "
        f"served bundle `{champ['bundle_sha256'][:12]}` (registry version {champ['registry_version']}).",
        "",
        f"Cross-validation: rolling origin by year, test years 2022 to 2024. Test: 2025, {sp['test_offers']} offers in "
        f"{sp['test_cascades']} cascades (acceptance rate {sp['test_acceptance_rate']:.1%}), scored once.",
        "",
        "| Model | CV Brier | CV AUC | 2025 Brier | 2025 AUC | 2025 calibration error |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        f"Best baseline by cross-validation (rule step 1): `{champ['best_baseline_by_cv']}`. "
        f"Learner promoted: **{'yes' if champ['promoted_learner'] else 'no'}**. Promotion checks on 2025:",
        "",
        "| Check (PROMOTION_RULE.md) | Result | Value |",
        "|---|---|---|",
        *checks,
        "",
        f"How much signal the generator puts into the 2025 offers (AUC of its own true acceptance probability, "
        f"which uses who the person is; `eval/` only): {doc['signal_in_the_data']['auc_of_true_probability']:.3f}.",
        "",
        f"Replay of the 2025 sick calls ({rp['replicates']} simulated runs; mean, and the middle 95 % of runs in brackets; "
        f"up to {rp['max_asks']} people asked, {rp['window_minutes']} minutes each; C2-checked candidate pool; "
        f"Gini over {rp['population_for_gini']} physicians who may cover):",
        "",
        "| Policy | Time to fill (min) | Cover-burden Gini | Escalation rate | People asked per filled gap |",
        "|---|---|---|---|---|",
        *replay,
        "",
        "Paired difference to the previous stand-in (b), same random draws in every run:",
        "",
        "| Policy | Time to fill (min) | Gini | Escalation rate | People asked per filled gap |",
        "|---|---|---|---|---|",
        *paired,
        C5_END,
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Write or check the table."""
    doc = json.loads((ROOT / "eval" / "results" / "benchmark.json").read_text(encoding="utf-8"))
    text = DOC.read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    new = text[:start] + table(doc) + text[end:]
    c3 = json.loads((ROOT / "eval" / "results" / "c3.json").read_text(encoding="utf-8"))
    card = CARD.read_text(encoding="utf-8")
    c_start, c_end = card.index(C3_START), card.index(C3_END) + len(C3_END)
    new_card = card[:c_start] + c3_tables(c3) + card[c_end:]
    c4 = json.loads((ROOT / "eval" / "results" / "c4.json").read_text(encoding="utf-8"))
    card4 = C4_CARD.read_text(encoding="utf-8")
    s4, e4 = card4.index(C4_START), card4.index(C4_END) + len(C4_END)
    new_card4 = card4[:s4] + c4_tables(c4) + card4[e4:]
    c5 = json.loads((ROOT / "eval" / "results" / "c5.json").read_text(encoding="utf-8"))
    card5 = C5_CARD.read_text(encoding="utf-8")
    s5, e5 = card5.index(C5_START), card5.index(C5_END) + len(C5_END)
    new_card5 = card5[:s5] + c5_tables(c5) + card5[e5:]
    if "--check" in argv:
        if new != text or new_card != card or new_card4 != card4 or new_card5 != card5:
            print("docs/ARCHITECTURE.md §17.1 or a model card is out of date; run eval/render_tables.py")
            return 1
        return 0
    DOC.write_text(new, encoding="utf-8")
    CARD.write_text(new_card, encoding="utf-8")
    C4_CARD.write_text(new_card4, encoding="utf-8")
    C5_CARD.write_text(new_card5, encoding="utf-8")
    print("rendered §17.1 and the C3, C4 and C5 model card tables")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
