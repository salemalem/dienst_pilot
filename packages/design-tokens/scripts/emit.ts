/** Turns resolved tokens into the three outputs: CSS variables, a Tailwind v4 theme, a native module. */
import { SHIFT_TYPES, THEMES, type Resolved, type ThemeId, type TypeStyle } from "./source.ts";

const HEADER = (r: Resolved, what: string): string =>
  `/* ${r.name} design tokens v${r.version}: ${what}.\n` +
  ` * GENERATED by packages/design-tokens/scripts/build.ts from\n` +
  ` * design/reference/design-system/project/tokens.json. Do not edit by hand. */\n`;

const NUMERIC = /^(num-|grid-letter)/;

function fontShorthand(s: TypeStyle): string {
  return `${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${s.family})`;
}

function colorDecls(r: Resolved, theme: ThemeId): string[] {
  return Object.entries(r.colors[theme]).map(([name, value]) => {
    const alias = r.aliases[name]?.[theme];
    return `  --${name}: ${alias === undefined ? value : `var(--${alias})`};`;
  });
}

/** CSS custom properties. Light on :root, dark under the `dp-dark` class (on <html> or any container). */
export function toCss(r: Resolved): string {
  const fontFaces = r.fonts.map(
    (f) =>
      `@font-face {\n  font-family: "${f.family}";\n  src: url("./${f.file}") format("woff2");\n` +
      `  font-weight: ${f.weight};\n  font-style: ${f.style};\n  font-display: swap;\n}\n`,
  );
  const shadow = (t: ThemeId): string[] =>
    Object.entries(r.shadows[t]).map(([n, v]) => `  --${n}: ${v};`);
  const plain = (rec: Record<string, string>): string[] =>
    Object.entries(rec).map(([n, v]) => `  --${n}: ${v};`);
  const type = r.typeStyles.flatMap((s) => [
    `  --type-${s.name}: ${fontShorthand(s)};`,
    ...(s.letterSpacing === undefined ? [] : [`  --type-${s.name}-tracking: ${s.letterSpacing};`]),
  ]);
  const root = [
    "  color-scheme: light;",
    ...colorDecls(r, "light"),
    ...shadow("light"),
    ...plain(r.spacing),
    ...plain(r.radius),
    ...plain(r.size),
    ...Object.entries(r.families).map(([n, v]) => `  --font-${n}: ${v};`),
    ...type,
  ];
  const dark = ["  color-scheme: dark;", ...colorDecls(r, "dark"), ...shadow("dark")];
  const classes = r.typeStyles.map((s) => {
    const lines = [`  font: var(--type-${s.name});`];
    if (s.letterSpacing !== undefined)
      lines.push(`  letter-spacing: var(--type-${s.name}-tracking);`);
    if (NUMERIC.test(s.name)) lines.push("  font-variant-numeric: tabular-nums;");
    return `.${s.name} {\n${lines.join("\n")}\n}\n`;
  });
  return [
    HEADER(r, "CSS custom properties (light on :root, dark under .dp-dark)"),
    ...fontFaces,
    `:root {\n${root.join("\n")}\n}\n`,
    `.dp-dark {\n${dark.join("\n")}\n}\n`,
    "/* Type style classes */\n",
    ...classes,
  ].join("\n");
}

/**
 * Tailwind v4 theme. Utilities point at the CSS variables from tokens.css, so `dp-dark` switches
 * them too. Tailwind's default palette is removed: only token colours exist (bg-paper, text-ink,
 * bg-shift-frueh ...). Load tokens.css before this file.
 */
export function toTailwind(r: Resolved): string {
  const v = (prefix: string, names: string[], target = (n: string): string => n): string[] =>
    names.map((n) => `  --${prefix}-${n}: var(--${target(n)});`);
  const spacing = Object.keys(r.spacing).map(
    (n) => `  --spacing-${n.replace(/^space-/, "")}: var(--${n});`,
  );
  const radius = Object.keys(r.radius).map(
    (n) => `  --radius-${n.replace(/^radius-/, "")}: var(--${n});`,
  );
  const shadow = Object.keys(r.shadows.light).map(
    (n) => `  --shadow-${n.replace(/^shadow-/, "")}: var(--${n});`,
  );
  const lines = [
    "  --color-*: initial;",
    ...v("color", Object.keys(r.colors.light)),
    "  --font-*: initial;",
    ...Object.keys(r.families).map((n) => `  --font-${n}: var(--font-${n});`),
    ...spacing,
    "  --radius-*: initial;",
    ...radius,
    "  --shadow-*: initial;",
    ...shadow,
  ];
  return `${HEADER(r, "Tailwind v4 theme")}\n@theme inline {\n${lines.join("\n")}\n}\n`;
}

const camel = (s: string): string => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const px = (s: string): number => {
  const m = /^(-?\d+(?:\.\d+)?)px$/.exec(s);
  if (m?.[1] === undefined) throw new Error(`Expected a px length, got "${s}"`);
  return Number(m[1]);
};

/** A TypeScript module with plain values for React Native, which cannot read CSS variables. */
export function toNative(r: Resolved): string {
  const colors = Object.fromEntries(
    THEMES.map((t) => [
      t,
      Object.fromEntries(Object.entries(r.colors[t]).map(([n, v]) => [camel(n), v])),
    ]),
  );
  const shadows = Object.fromEntries(
    THEMES.map((t) => [
      t,
      Object.fromEntries(
        Object.entries(r.shadows[t]).map(([n, v]) => [camel(n.replace(/^shadow-/, "")), v]),
      ),
    ]),
  );
  const strip = (rec: Record<string, string>, prefix: RegExp): Record<string, number> =>
    Object.fromEntries(Object.entries(rec).map(([n, v]) => [camel(n.replace(prefix, "")), px(v)]));
  const fontFamily = r.fonts[0]?.family ?? "System";
  const type = Object.fromEntries(
    r.typeStyles.map((s) => {
      const size = px(s.fontSize);
      // Unitless line height (e.g. "1") is a multiple of the font size.
      const lineHeight = /px$/.test(s.lineHeight) ? px(s.lineHeight) : size * Number(s.lineHeight);
      const style: Record<string, unknown> = {
        fontFamily,
        fontSize: size,
        lineHeight,
        fontWeight: String(s.fontWeight),
      };
      if (s.letterSpacing?.endsWith("em")) {
        style.letterSpacing = Math.round(parseFloat(s.letterSpacing) * size * 100) / 100;
      }
      if (NUMERIC.test(s.name)) style.fontVariant = ["tabular-nums"];
      return [camel(s.name), style];
    }),
  );
  const json = (x: unknown): string => JSON.stringify(x, null, 2);
  return `// ${r.name} design tokens v${r.version}: native module.
// GENERATED by packages/design-tokens/scripts/build.ts from
// design/reference/design-system/project/tokens.json. Do not edit by hand.

export const shiftTypes = ${json(SHIFT_TYPES)} as const;

export const colors = ${json(colors)} as const;

/** CSS box-shadow strings; React Native (New Architecture) accepts them as \`boxShadow\`. */
export const shadows = ${json(shadows)} as const;

export const spacing = ${json(strip(r.spacing, /^space-/))} as const;

export const radius = ${json(strip(r.radius, /^radius-/))} as const;

export const size = ${json(strip(r.size, /^$/))} as const;

export const fontFamily = ${json(fontFamily)};

export const typography = ${json(type)} as const;
`;
}
